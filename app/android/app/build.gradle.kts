import java.util.Properties
import java.io.FileInputStream

plugins {
    id("com.android.application")
    // The Flutter Gradle Plugin must be applied after the Android and Kotlin Gradle plugins.
    id("dev.flutter.flutter-gradle-plugin")
}

// Release signing config is read from android/key.properties (git-ignored). If it's
// absent (e.g. a fresh clone with no keystore), release falls back to debug signing
// so `flutter run --release` still works locally.
val keystorePropertiesFile = rootProject.file("key.properties")
val keystoreProperties = Properties()
if (keystorePropertiesFile.exists()) {
    keystoreProperties.load(FileInputStream(keystorePropertiesFile))
}

android {
    namespace = "site.agniv.relay"
    compileSdk = 36 // file_picker's flutter_plugin_android_lifecycle requires >= 36
    ndkVersion = flutter.ndkVersion

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    defaultConfig {
        applicationId = "site.agniv.relay"
        // You can update the following values to match your application needs.
        // For more information, see: https://flutter.dev/to/review-gradle-config.
        minSdk = flutter.minSdkVersion
        targetSdk = 36 // target the latest Android (API 36) for current-OS compatibility
        versionCode = flutter.versionCode
        versionName = flutter.versionName
    }

    signingConfigs {
        if (keystorePropertiesFile.exists()) {
            create("release") {
                keyAlias = keystoreProperties["keyAlias"] as String
                keyPassword = keystoreProperties["keyPassword"] as String
                storeFile = file(keystoreProperties["storeFile"] as String)
                storePassword = keystoreProperties["storePassword"] as String
            }
        }
    }

    buildTypes {
        release {
            // Sign with the real release keystore when present (android/key.properties),
            // otherwise fall back to debug keys so a fresh clone still builds.
            signingConfig = if (keystorePropertiesFile.exists())
                signingConfigs.getByName("release")
            else
                signingConfigs.getByName("debug")
            // R8 code shrinking + obfuscation ON (Play flags DEX optimization below
            // 25%). Keep rules for the media stack are in proguard-rules.pro.
            isMinifyEnabled = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
            // Resource shrinking stays OFF: it strips resources only referenced by
            // name at runtime (audio_service's notification control drawables, via
            // getIdentifier), which breaks the media-session / lock-screen controls.
            isShrinkResources = false
        }
    }
}

kotlin {
    compilerOptions {
        jvmTarget = org.jetbrains.kotlin.gradle.dsl.JvmTarget.JVM_17
    }
}

flutter {
    source = "../.."
}

dependencies {
    // Provides android.support.v4.media.* (MediaBrowserCompat / MediaControllerCompat)
    // so MainActivity can dispatch voice "play X" (MEDIA_PLAY_FROM_SEARCH) to the
    // audio_service media session. Same artifact the audio_service plugin uses.
    implementation("androidx.media:media:1.7.0")
}
